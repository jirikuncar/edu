// One-shot: pull capital city coordinates from Natural Earth (public domain)
// and emit src/atlas/capitals.js, so the map can mark the answer offline.
import { writeFile } from "node:fs/promises";
import { COUNTRIES } from "../src/atlas/countries.js";

const SOURCE =
  "https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ne_10m_populated_places_simple.geojson";

const places = (await (await fetch(SOURCE)).json()).features;
console.log(`${places.length} places downloaded`);

const plain = (value) =>
  (value ?? "")
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .toLowerCase()
    .replace(/[^a-z]/g, "");

// Several countries name a capital that is not the one Natural Earth flags
// as primary (Sucre, Amsterdam, Yamoussoukro...). Match on the name we
// actually show, and only fall back to the flagged capital.
/* Natural Earth has no entry for Nauru's seat of government. */
const MANUAL = {
  NR: { name: "Yaren", lon: 166.921, lat: -0.548 },
};

const rows = [];
const missing = [];
const notes = [];

for (const country of COUNTRIES) {
  const wanted = plain(country.cap.en);
  const inCountry = places.filter(
    (place) => (place.properties.iso_a2 ?? "").toUpperCase() === country.a2,
  );
  const named = inCountry.find(
    (place) =>
      plain(place.properties.name) === wanted ||
      plain(place.properties.nameascii) === wanted ||
      plain(place.properties.namealt) === wanted,
  );
  const flagged = inCountry.find((place) =>
    /Admin-0 capital/.test(place.properties.featurecla ?? ""),
  );
  const loose =
    !named && !flagged
      ? places.find(
          (place) =>
            plain(place.properties.name) === wanted &&
            /Admin-0 capital/.test(place.properties.featurecla ?? ""),
        )
      : null;

  const manual = MANUAL[country.a2];
  if (manual) {
    rows.push(`  ${country.a2}: [${manual.lon}, ${manual.lat}], // ${manual.name} (manual)`);
    continue;
  }

  const hit = named ?? flagged ?? loose;
  if (!hit) {
    missing.push(`${country.a2} ${country.name.en} (${country.cap.en})`);
    continue;
  }
  if (!named) notes.push(`${country.a2} ${country.cap.en} -> ${hit.properties.name}`);
  const [lon, lat] = hit.geometry.coordinates;
  rows.push(
    `  ${country.a2}: [${lon.toFixed(3)}, ${lat.toFixed(3)}], // ${hit.properties.name}`,
  );
}

await writeFile(
  new URL("../src/atlas/capitals.js", import.meta.url),
  `/* Capital city coordinates [lon, lat], from Natural Earth's 10m populated
   places (public domain). Generated by scripts/fetch-capitals.mjs. */

export const CAPITALS = {
${rows.join("\n")}
};
`,
);

console.log(`${rows.length} capitals written`);
if (notes.length) console.log("matched by fallback:\n  " + notes.join("\n  "));
if (missing.length) console.log("MISSING:\n  " + missing.join("\n  "));
